function standardPegs(): PegDef[] {
  const pegs: PegDef[] = [];
  const startY = 52;
  const chuteTop = 275 - 26;
  const rowSpacing = (chuteTop - startY - 10) / 5;
  let id = 0;
  for (let row = 0; row < 5; row++) {
    const cols = row % 2 === 0 ? 7 : 6;
    const colSpacing = 600 / (cols + 1);
    for (let col = 1; col <= cols; col++) {
      const x = col * colSpacing + (row % 2 === 1 ? colSpacing * 0.15 : 0);
      const y = startY + row * rowSpacing;
      let kind: PegDef['kind'] = 'gold';
      if (row === 1 && (col === 2 || col === cols - 1)) kind = 'splitter';
      else if (row === 2 && col === Math.ceil(cols / 2)) kind = 'bumper';
      pegs.push({ id: id++, x, y, kind, radius: kind === 'bumper' ? 11 : 5.5 });
    }
  }
  return pegs;
}

